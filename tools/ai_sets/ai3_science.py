def phen(g):
    s = set(g)
    if s == {'A', 'B'}:
        return 'AB'
    if 'A' in s:
        return 'A'
    if 'B' in s:
        return 'B'
    return 'O'


def can_have(f, m, child):
    return any(phen(x + y) == child for gf in ALLELE[f] for gm in ALLELE[m] for x in gf for y in gm)


