def wind_from(dx, dy):
    """station at (dx, dy) relative to the centre (x east, y north); ccw flow -> wind direction it blows FROM"""
    import math
    vx, vy = -dy, dx                         # counter-clockwise tangent
    ang = math.degrees(math.atan2(-vx, -vy)) % 360   # from-direction, clockwise from north
    names = ['北', '東北', '東', '東南', '南', '西南', '西', '西北']
    return names[int((ang + 22.5) // 45) % 8]


