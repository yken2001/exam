def fig_pedigree():
    fig, ax = plt.subplots(figsize=(5.6, 3.6))
    s = 0.36

    def person(x, y, male, aff, label):
        if male:
            ax.add_patch(Rectangle((x - s, y - s), 2 * s, 2 * s, facecolor='black' if aff else 'white', edgecolor='black', linewidth=1.4))
        else:
            ax.add_patch(Circle((x, y), s, facecolor='black' if aff else 'white', edgecolor='black', linewidth=1.4))
        ax.text(x, y - s - 0.32, label, ha='center', va='top', fontsize=9)

    # generation I
    person(3, 6, True, True, 'Ⅰ-1')
    person(5, 6, False, True, 'Ⅰ-2')
    ax.plot([3 + s, 5 - s], [6, 6], color='black')
    ax.plot([4, 4], [6, 5.0], color='black')
    ax.plot([2, 6], [5.0, 5.0], color='black')
    # generation II
    ax.plot([2, 2], [5.0, 4.0 + s], color='black')
    ax.plot([6, 6], [5.0, 4.0 + s], color='black')
    person(2, 4, False, True, 'Ⅱ-2')
    person(6, 4, True, False, 'Ⅱ-3')
    person(0.2, 4, True, False, 'Ⅱ-1')
    ax.plot([0.2 + s, 2 - s], [4, 4], color='black')
    ax.plot([1.1, 1.1], [4, 3.0], color='black')
    ax.plot([0.2, 2.0], [3.0, 3.0], color='black')
    # generation III
    ax.plot([0.2, 0.2], [3.0, 2.0 + s], color='black')
    ax.plot([2.0, 2.0], [3.0, 2.0 + s], color='black')
    person(0.2, 2, True, True, 'Ⅲ-1')
    person(2.0, 2, False, False, 'Ⅲ-2')
    # legend
    ax.add_patch(Rectangle((7.4 - s / 1.5, 2.7 - s / 1.5), 2 * s / 1.5, 2 * s / 1.5, facecolor='white', edgecolor='black'))
    ax.text(7.8, 2.7, '正常男性', va='center', fontsize=8)
    ax.add_patch(Circle((7.4, 2.05), s / 1.5, facecolor='white', edgecolor='black'))
    ax.text(7.8, 2.05, '正常女性', va='center', fontsize=8)
    ax.add_patch(Rectangle((7.4 - s / 1.5, 1.4 - s / 1.5), 2 * s / 1.5, 2 * s / 1.5, facecolor='black', edgecolor='black'))
    ax.text(7.8, 1.4, '表現此性狀的男性', va='center', fontsize=8)
    ax.add_patch(Circle((7.4, 0.75), s / 1.5, facecolor='black', edgecolor='black'))
    ax.text(7.8, 0.75, '表現此性狀的女性', va='center', fontsize=8)
    ax.set_xlim(-0.5, 10)
    ax.set_ylim(0.2, 6.6)
    ax.set_aspect('equal')
    ax.axis('off')
    ax.set_title('某家族中一種性狀的遺傳譜系', fontsize=10)
    return b.save_fig(fig, 'q02.png')


