def fig_particles():
    rnd = np.random.RandomState(7)
    fig, axes = plt.subplots(1, 4, figsize=(9.0, 2.1))
    BL, WH, GR = 'black', 'white', '#9a9a9a'
    r = 0.38

    def atom(ax, x, y, c):
        ax.add_patch(Circle((x, y), r, facecolor=c, edgecolor='black', linewidth=1.0))

    def mol(ax, x, y, atoms, ang):
        dx, dy = 2 * r * math.cos(ang), 2 * r * math.sin(ang)
        for i, c in enumerate(atoms):
            atom(ax, x + i * dx, y + i * dy, c)

    spots = [(0.8, 1.0), (4.0, 1.3), (7.0, 0.9), (1.0, 3.6), (4.2, 3.9), (7.2, 3.5)]
    boxes = {
        '甲': [[GR]] * 6,
        '乙': [[BL, WH]] * 6,
        '丙': [[BL, WH]] * 3 + [[WH, GR, WH]] * 3,
        '丁': [[BL, BL]] * 3 + [[WH, WH]] * 3,
    }
    for ax, (name, mols) in zip(axes, boxes.items()):
        ax.add_patch(Rectangle((0, 0), 9.4, 5.0, fill=False, edgecolor='black', linewidth=1.2))
        for (x, y), m in zip(spots, mols):
            mol(ax, x, y, m, rnd.uniform(-0.4, 0.4))
        ax.set_xlim(-0.2, 9.6)
        ax.set_ylim(-0.2, 5.2)
        ax.set_aspect('equal')
        ax.axis('off')
        ax.set_title(name, fontsize=12)
    fig.text(0.5, -0.02, '●、○、灰色圓分別代表三種不同的原子，相連的原子表示一個分子', ha='center', fontsize=9)
    return b.save_fig(fig, 'q20.png')


