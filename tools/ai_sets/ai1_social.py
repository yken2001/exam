def item(stem, correct, distractors, explanation, check=None):
    assert len(distractors) == 3 and correct not in distractors and len(set(distractors)) == 3, stem[:20]
    if check is not None:
        ok, bad = check
        assert ok, f'computed value does not match: {stem[:30]}'
        assert not any(bad), f'a distractor equals the computed value: {stem[:30]}'
    items.append(dict(stem=stem, correct=correct, distractors=distractors, explanation=explanation))


