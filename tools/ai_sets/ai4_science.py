def daylength(lat, dec):
    phi, d = math.radians(lat), math.radians(dec)
    c = (math.sin(math.radians(-0.833)) - math.sin(phi) * math.sin(d)) / (math.cos(phi) * math.cos(d))
    c = max(-1.0, min(1.0, c))
    return 2 * math.degrees(math.acos(c)) / 15


